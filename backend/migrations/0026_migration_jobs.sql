CREATE TABLE IF NOT EXISTS migration_jobs (
    job_id UUID PRIMARY KEY,
    migration_id BIGINT NOT NULL REFERENCES migrations(id) ON DELETE CASCADE,
    execution_id UUID NOT NULL UNIQUE,
    parent_execution_id UUID,
    database_id TEXT NOT NULL REFERENCES managed_db_connections(id) ON DELETE CASCADE,
    actor_id TEXT NOT NULL REFERENCES platform_users(id) ON DELETE RESTRICT,
    actor_username TEXT NOT NULL,
    action TEXT NOT NULL CHECK (action IN ('execute', 'rollback', 'forward', 'resume_batch', 'revert_batch')),
    mode TEXT NOT NULL CHECK (mode IN ('normal', 'batch')),
    status TEXT NOT NULL CHECK (status IN ('pending', 'running', 'success', 'failed', 'partial', 'partially_reverted', 'uncertain')),
    batch_by_attribute TEXT,
    batch_size INTEGER CHECK (batch_size IS NULL OR batch_size > 0),
    target_scope_max TEXT,
    last_committed_batch INTEGER NOT NULL DEFAULT 0 CHECK (last_committed_batch >= 0),
    last_committed_cursor TEXT,
    committed_rows BIGINT NOT NULL DEFAULT 0 CHECK (committed_rows >= 0),
    attempt INTEGER NOT NULL DEFAULT 0 CHECK (attempt >= 0),
    max_retries INTEGER NOT NULL DEFAULT 3 CHECK (max_retries >= 0),
    next_retry_at TIMESTAMPTZ,
    trace_context JSONB NOT NULL DEFAULT '{}'::jsonb,
    error_message TEXT,
    sqlstate TEXT,
    enqueued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
