CREATE TABLE IF NOT EXISTS migration_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    migration_id BIGINT NOT NULL,
    database_id TEXT NOT NULL REFERENCES managed_db_connections(id) ON DELETE CASCADE,
    attempt_number INTEGER NOT NULL CHECK (attempt_number > 0),
    sql_snapshot TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED')),
    executed_by TEXT NOT NULL REFERENCES platform_users(id) ON DELETE RESTRICT,
    error_message TEXT,
    execution_ms BIGINT NOT NULL DEFAULT 0 CHECK (execution_ms >= 0),
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    UNIQUE (migration_id, attempt_number),
    FOREIGN KEY (migration_id, database_id) REFERENCES migrations(id, database_id) ON DELETE CASCADE
);
