CREATE TABLE IF NOT EXISTS migrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    database_id TEXT NOT NULL REFERENCES managed_db_connections(id) ON DELETE CASCADE,
    version BIGINT,
    title TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    sql_content TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('DRAFT', 'FAILED', 'APPLIED')),
    created_by TEXT NOT NULL REFERENCES platform_users(id) ON DELETE RESTRICT,
    updated_by TEXT NOT NULL REFERENCES platform_users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    applied_at TIMESTAMPTZ,
    UNIQUE (database_id, version),
    UNIQUE (id, database_id),
    CHECK (version IS NULL OR version > 0),
    CHECK ((status = 'APPLIED') = (version IS NOT NULL))
);
