CREATE TABLE migration_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    migration_id BIGINT NOT NULL,
    database_id TEXT NOT NULL,
    operation TEXT NOT NULL CHECK (operation IN ('APPLY', 'ROLLBACK', 'FORWARD')),
    revision BIGINT NOT NULL CHECK (revision > 0),
    target_run_id BIGINT,
    sql_snapshot TEXT NOT NULL,
    requested_by TEXT NOT NULL REFERENCES platform_users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL,
    FOREIGN KEY (migration_id, database_id) REFERENCES migrations (id, database_id) ON DELETE CASCADE,
    FOREIGN KEY (target_run_id, migration_id) REFERENCES migration_runs (id, migration_id) ON DELETE CASCADE,
    CHECK ((operation = 'APPLY') = (target_run_id IS NULL))
);
